// Couples course, classes 15–21 — Tiramisu, Sombrero complicado doble, Juana la
// Cubana, El Uno semi complicado, Dedo, Santiago, the two solo sequences, and
// the all-moves demo class.
//
// Source of every number: SALSA_COUPLES_SPEC_PART3.md.
//
// Two structural oddities in this range:
//   * Class 20 teaches *leaving and rejoining* your partner rather than a figure,
//     so it yields two solo sequences plus the release-and-return skill, and its
//     two full-tempo clips have a natural seam where the teachers announce the
//     second sequence.
//   * Class 21 teaches nothing new. It is one continuous demo song, so it gets a
//     class-level clip and a call sheet naming each move as it is danced —
//     exactly how Class 15 of the steps course is handled. Calls there are not
//     teaching sources.
//
// Seven things that are not obvious from the spec and that a later pass will
// otherwise re-discover the hard way:
//
//  1. CLASSES 15 AND 16 CARRY CONTAINER DURATIONS (562.109 / 674.888, ffprobed
//     against data/cache/salsa/videos/); classes 17–21 carry their YouTube
//     *metadata* duration — 17: 827, 18: 681, 19: 872, 20: 958, 21: 450 — which is
//     rounded to the second. Their videos have since been downloaded, so a
//     container value is now obtainable for all five; 20 was ffprobed at 958.52
//     and the metadata value was kept deliberately. There is no `warning` field
//     on `SalsaClass`, so this note is the only place the distinction can live.
//
//  2. EVERY WINDOW IN THIS RANGE IS NOW CUT. The ten windows that were once
//     missing — class 17 (el-uno-semi-complicado slow + fast, juana-la-cubana
//     slow), 18 (dedo slow), 19 (santiago slow), 20 (both sequences slow + fast,
//     shared onto release-and-return) and 21 (the class-level demo) — exist in
//     frontend/public/clips/salsa/couples/ and are all `16/9`, because they are
//     cut from class videos rather than from shorts. Nothing in this file is
//     `null` and no `ClipPair` carries a `missingReason`. Class 21 is the one
//     genuine absence and it is not expressible: the class has no `count`
//     chapter, so no counted grain exists to cut, but `SalsaClass.clip` is a
//     single `SalsaClip` rather than a `ClipPair` — there is no slow side to set
//     to `null` and nowhere to hang a `missingReason`. That fact is stated in the
//     class clip's `caveat` and in the `c21-demo` segment instead (K21-e).
//
//  3. THE SPEC'S `angle` CHAPTERS HAVE NO `SegmentRole`. `SegmentRole` is
//     teach/count/music/review/skip, so each side-view chapter is recorded as
//     `count` or `music` according to what the transcript says its tempo is
//     (counted in 15/16/17/18, full tempo in 19), the side view stays in the
//     `label`, and the segment carries a `warning` saying the mapping happened.
//     No type was widened for it.
//
//  4. THERE ARE NO `alternates`. The spec wants each move's in-class music window
//     published as an alternate to hedge the untranscribed shorts, but
//     CLIP_MANIFEST_COUPLES.md cuts no alternate files and `SalsaClip.src` is
//     required — a `src` pointing at a file that was never cut would be a lie.
//     Every alternate window is recorded as a `notes` entry instead, with its
//     anchor, so it survives.
//
//  5. THE FIVE OFFICIAL SHORTS END ON THEIR CONTAINER DURATION, not the spec's
//     rounded second: 42.494 / 37.474 / 47.274 / 37.694 / 45.954. The player
//     prints `round(end - start)` as the clip's length, so the rounded values
//     would caption a wrong duration.
//
//  6. CUES RUN leader → follower → both WITHIN EVERY MOVE (R4, and salsa-couples.ts
//     "Leader cues come first"), each group in transcript order. The page filters
//     by role anyway, so nothing is lost visually and the array is unambiguous.
//
//  7. CROSS-PART ID RECONCILIATION. Parts 1–2 own the ids, so the spec's guesses
//     were rewritten: `exhibela` → `exhibela-crossing`, `coca-cola` → `cocacola`,
//     `alarde` → dropped (the course's Alarde move is Class 10's
//     `enchufla-doble-alarde` and the transcript says plain "Enchufla Alarde", so
//     the edge is a note, not a `composedOf`), `left-turn` / `right-turn` →
//     dropped (the steps course teaches a side *and* a front-and-back version of
//     each and nothing here says which, K20-h). Class 21's one usable instruction
//     (@387.24, "you can release your partner a bit more") is a `notes` entry on
//     `release-and-return` rather than a cue, because a cue's `sourceVideo` must
//     appear in one of its move's `sources` and Class 21 is deliberately not a
//     teaching source (K21-f).

